import html2canvas from 'html2canvas'

const formatAmount = (value) => {
  const num = Number(value || 0)
  return num.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

const formatDate = (value) => {
  if (!value) return ''
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return ''
  return date.toLocaleDateString('en-GB')
}

const formatTimestamp = (value = new Date()) => {
  const date = value instanceof Date ? value : new Date(value)
  return date.toLocaleString('en-GB', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: true,
  })
}

const getMonthLabel = (monthKey) => {
  if (!monthKey) return ''
  const date = new Date(`${monthKey}-01T00:00:00`)
  if (Number.isNaN(date.getTime())) return ''
  return date.toLocaleDateString('en-GB', { month: 'short', year: 'numeric' })
}

const getSalaryData = (data) => {
  return data?.salaryStructure || data?.salary || data?.payslipSalary || data?.payslip?.salaryStructure || {}
}

const getProfileData = (data) => {
  return data?.profile || data?.user || data || {}
}

const calculateTotals = (salary) => {
  const basisSalary = Number(salary.basisSalary || 0)
  const houseRentAllowance = Number(salary.houseRentAllowance || 0)
  const medicalAllowance = Number(salary.medicalAllowance || 0)
  const educationAllowance = Number(salary.educationAllowance || 0)
  const otherAllowance = Number(salary.otherAllowance || 0)
  const epf = Number(salary.epf || 0)
  const esic = Number(salary.esic || 0)
  const tds = Number(salary.tds || 0)
  const otherDeductions = Number(salary.otherDeductions || 0)

  const totalEarningsRaw = basisSalary + houseRentAllowance + medicalAllowance + educationAllowance + otherAllowance
  const totalDeductionsRaw = epf + esic + tds + otherDeductions

  const totalEarnings = Number.isFinite(salary.totalEarningsOverride)
    ? Number(salary.totalEarningsOverride)
    : totalEarningsRaw
  const totalDeductions = Number.isFinite(salary.totalDeductionsOverride)
    ? Number(salary.totalDeductionsOverride)
    : totalDeductionsRaw
  const netPay = Number.isFinite(salary.netPayOverride)
    ? Number(salary.netPayOverride)
    : Math.max(0, totalEarnings - totalDeductions)

  return {
    basisSalary,
    houseRentAllowance,
    medicalAllowance,
    educationAllowance,
    otherAllowance,
    epf,
    esic,
    tds,
    otherDeductions,
    totalEarnings,
    totalDeductions,
    netPay,
  }
}

