const renderPayslipCanvas = async (data) => {
  const wrapper = document.createElement('div')
  wrapper.style.position = 'fixed'
  wrapper.style.left = '-9999px'
  wrapper.style.top = '0'
  wrapper.style.zIndex = '-1'

  const node = createPayslipNode(data)
  wrapper.appendChild(node)
  document.body.appendChild(wrapper)

  const canvas = await html2canvas(node, {
    backgroundColor: '#ffffff',
    scale: 2,
    useCORS: true,
  })

  document.body.removeChild(wrapper)
  return canvas
}

export const downloadPayslipImage = async (data, filename = 'payslip.png') => {
  const canvas = await renderPayslipCanvas(data)
  const link = document.createElement('a')
  link.href = canvas.toDataURL('image/png')
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
}

export const openPayslipImage = async (data) => {
  const canvas = await renderPayslipCanvas(data)
  const dataUrl = canvas.toDataURL('image/png')
  const win = window.open('')
  if (!win) return
  win.document.write(`<title>Payslip</title><img src="${dataUrl}" style="max-width:100%;height:auto;" />`)
  win.document.close()
}
